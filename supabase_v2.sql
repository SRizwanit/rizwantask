-- ১) পেইজ-প্রুফ: রিভিউ স্ট্যাটাস (pending = অপেক্ষমাণ, approved = অনুমোদিত, correction = সংশোধন দরকার)
alter table public.page_proofs add column if not exists created_at    timestamptz default now();
alter table public.page_proofs add column if not exists review_status text        not null default 'pending';
alter table public.page_proofs add column if not exists review_note   text;
alter table public.page_proofs add column if not exists reviewed_at    timestamptz;
alter table public.page_proofs add column if not exists rate           numeric;      -- অনুমোদনের সময়ের রেট (টাকা/পেইজ)
create index if not exists page_proofs_user_idx   on public.page_proofs (user_id);
create index if not exists page_proofs_status_idx on public.page_proofs (review_status);
create index if not exists page_proofs_created_ix on public.page_proofs (created_at);

-- ২) কিতাব: পেইজ-প্রতি রেট (খালি = ডিফল্ট রেট) ও মোট পেইজ সংখ্যা (অগ্রগতির বারের জন্য)
alter table public.books add column if not exists page_rate   numeric;
alter table public.books add column if not exists total_pages integer;

-- ৩) সেটিংস: ডিফল্ট রেট, ন্যূনতম পেমেন্ট, ভুলের সতর্কতা
alter table public.app_settings add column if not exists page_rate  numeric not null default 0.20;  -- টাকা/পেইজ
alter table public.app_settings add column if not exists min_payout numeric not null default 50;    -- ন্যূনতম পেমেন্ট রিকোয়েস্ট (টাকা)
alter table public.app_settings add column if not exists warn_pct   integer not null default 20;    -- সংশোধনের হার (%) এর বেশি হলে ইউজারকে সতর্কবার্তা
alter table public.app_settings add column if not exists warn_min   integer not null default 5;     -- কমপক্ষে এতগুলো রিভিউ হলে তবেই সতর্কবার্তা

-- ৪) ইউজার: ব্লক ও সর্বশেষ সক্রিয় সময়
