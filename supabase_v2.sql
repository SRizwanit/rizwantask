alter table public.app_users add column if not exists blocked_reason text;
alter table public.app_users add column if not exists last_active_at timestamptz;

-- ৫) পেমেন্ট রিকোয়েস্ট ও ইতিহাস (status: requested / paid / rejected)
create table if not exists public.payments (
  id           bigint generated by default as identity primary key,
  user_id      text not null,
  user_name    text,
  amount       numeric not null,
  pages        integer,
  method       text,
  number       text,
  status       text not null default 'requested',
  note         text,                          -- অ্যাডমিনের নোট / ট্রানজেকশন আইডি / বাতিলের কারণ
  created_at   timestamptz not null default now(),
  processed_at timestamptz
);
create index if not exists payments_user_idx   on public.payments (user_id);
create index if not exists payments_status_idx on public.payments (status);

-- ৬) ঘোষণা / নোটিশ (user_id খালি = সবার জন্য, নইলে নির্দিষ্ট ইউজারের জন্য)
create table if not exists public.notices (
  id         bigint generated by default as identity primary key,
  user_id    text,
  title      text not null,
  body       text,
  kind       text not null default 'notice',   -- notice / review / payment
  created_at timestamptz not null default now()
);
create index if not exists notices_user_idx on public.notices (user_id);

-- ৭) কার্যকলাপের লগ (কে কখন কী করল)
create table if not exists public.activity_log (
  id         bigint generated by default as identity primary key,
  user_id    text,
  user_name  text,
  action     text not null,
  detail     text,
  created_at timestamptz not null default now()
);
create index if not exists activity_log_user_idx on public.activity_log (user_id);
create index if not exists activity_log_time_idx on public.activity_log (created_at desc);

