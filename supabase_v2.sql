-- ৯) দ্রুত গণনার ফাংশন (না চালালেও অ্যাপ নিজে গুনে নেয়; শুধু দ্রুত করার জন্য)
-- কিতাব অনুযায়ী মোট প্রুফড পেইজ (অগ্রগতির বার)
create or replace function public.book_proof_counts()
returns table(book_id text, n bigint)
language sql stable
as $$ select book_id::text, count(*) from public.page_proofs group by book_id; $$;
grant execute on function public.book_proof_counts() to anon, authenticated;

-- লিডারবোর্ড (সংশোধন-দরকার পেইজ বাদে); p_since = কোন সময় থেকে (null = সব সময়)
create or replace function public.leaderboard(p_since timestamptz default null)
returns table(user_id text, n bigint)
language sql stable
as $$
  select user_id::text, count(*) from public.page_proofs
  where review_status <> 'correction' and (p_since is null or created_at >= p_since)
  group by user_id order by count(*) desc limit 200;
$$;
grant execute on function public.leaderboard(timestamptz) to anon, authenticated;
